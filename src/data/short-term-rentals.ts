export function getShortTermRentals(destination: string): ShortTermRental[] {
  const key = destination.trim().toLowerCase().split(",")[0] || "barcelona";
  const rentals = cityProfiles[key] ?? fallbackRentals;

  return rentals.map((rental, index) => ({
    ...rental,
    id: `rental-${key}-${index}`,
    city: destination || "Barcelona",
    location: `${destination || "Barcelona"} · ${rental.neighborhood}`,
    bookingLink: rental.bookingLink ?? "https://www.booking.com/searchresults.html",
    lastChecked: new Date().toISOString(),
  }));
}
